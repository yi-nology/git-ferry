// Package release 承载"发版纪律"相关的机械门禁。
//
// 背景:本项目把「报告与事实相反」列为最高优先级缺陷类别 —— 而
// **版本号本身也是一种报告**。一轮包含破坏性契约变更的改动如果发成
// minor/patch,版本号就在说谎:下游(MVS、升级决策、semver 工具链)会
// 按"兼容"来假设,升级时踩坑。
//
// 2026-10 那轮(v1.36.0~v1.38.0)就是这么发的:里面同时有
// "history +detail 查不到从 200 空列表变 404"、"auth status 退出码
// 0 变 1"、"--csv 输出去掉 JSON 信封"这类破坏性变更,却连发三个 minor。
//
// 这个包把纪律变成**可执行的检查**,而不是靠人记:
//   - 破坏性变更必须显式标记,且标记了就必须是 major;
//   - major 版本必须给出迁移指引;
//   - 公开契约(OpenAPI)删了 path / 请求参数 ⇒ 必须 major。
